let currentLocale = DEFAULT_LOCALE;
let initialized = false;

export function getLocale() {
    return currentLocale;
}

export function t(key, params) {
    const table = messages[currentLocale] || messages[DEFAULT_LOCALE];
    let s = table[key];
    if (s === undefined) {
        s = messages[DEFAULT_LOCALE][key];
        if (s === undefined) {
            if (typeof console !== 'undefined' && console.warn) {
                console.warn('[i18n] missing key:', key);
            }
            return key;
        }
    }
    if (params && typeof s === 'string') {
        s = s.replace(/\{(\w+)\}/g, (_, k) => {
            const v = params[k];
            return v === undefined || v === null ? '' : String(v);
        });
    }
    return s;
}

export function setLocale(locale) {
    if (!SUPPORTED.includes(locale)) locale = DEFAULT_LOCALE;
    currentLocale = locale;
    try {
        localStorage.setItem(STORAGE_KEY, locale);
    } catch (_) { /* ignore */ }
    document.documentElement.lang = locale;
    applyI18n();
    try {
        window.dispatchEvent(new CustomEvent('localechange', { detail: { locale } }));
    } catch (_) { /* ignore */ }
}

export function initI18n() {
    if (initialized) return currentLocale;
    initialized = true;

    let loc = null;

    // 1) URL ?lang=
    try {
        const params = new URL(window.location.href).searchParams;
        const fromUrl = params.get('lang');
        if (fromUrl && SUPPORTED.includes(fromUrl)) loc = fromUrl;
    } catch (_) { /* ignore */ }

    // 2) localStorage
    if (!loc) {
        try {
            const stored = localStorage.getItem(STORAGE_KEY);
            if (stored && SUPPORTED.includes(stored)) loc = stored;
        } catch (_) { /* ignore */ }
    }

    // 3) navigator.language
    if (!loc) {
        const nav = (navigator.language || '').toLowerCase();
        loc = nav.startsWith('en') ? 'en' : DEFAULT_LOCALE;
    }

    currentLocale = loc;
    document.documentElement.lang = loc;
    return loc;
}

export function applyI18n(root) {
    const r = root || document;
    r.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) el.textContent = t(key);
    });
    r.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (key) el.innerHTML = t(key);
    });
    r.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key) el.setAttribute('placeholder', t(key));
    });
    r.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (key) el.setAttribute('title', t(key));
    });
    r.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria-label');
        if (key) el.setAttribute('aria-label', t(key));
    });
}

export function mountLanguageSwitcher(target) {
    const el = typeof target === 'string' ? document.getElementById(target) : target;
    if (!el) return;

    const render = () => {
        el.innerHTML = `
      <div class="lang-switch" role="group" aria-label="${t('lang.switch')}">
        <button type="button" data-lang="zh-CN" class="${currentLocale === 'zh-CN' ? 'is-active' : ''}">${t('lang.zh')}</button>
        <button type="button" data-lang="en" class="${currentLocale === 'en' ? 'is-active' : ''}">${t('lang.en')}</button>
      </div>
    `;
        el.querySelectorAll('[data-lang]').forEach(btn => {
            btn.addEventListener('click', () => {
                setLocale(btn.getAttribute('data-lang'));
            });
        });
    };

    render();
    // 语言变化时重新渲染自身
    window.addEventListener('localechange', render);
}